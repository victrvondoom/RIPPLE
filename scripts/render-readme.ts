/**
 * Renders the README's pack block (between <!-- packs:start --> and <!-- packs:end -->) from the pack registry, so the
 * count and list of domains can never drift from the code. Usage: npx tsx scripts/render-readme.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { extendedRegistry } from '../src/server/packs/registry.js';
import { SYSTEMS } from '../src/server/capabilities/catalog.js';

const packs = extendedRegistry().all();
const rows = SYSTEMS.map((s) => {
  const ps = packs.filter((p) => p.system === s.id);
  return ps.length ? `| ${s.name} | ${ps.map((p) => `${p.name} (\`${p.id}\`${p.tier === 'core' ? ', core' : ''})`).join(', ')} |` : null;
}).filter(Boolean);
const block = [
  '<!-- packs:start -->',
  '<!-- generated by scripts/render-readme.ts from the pack registry; do not edit by hand -->',
  `RIPPLE is one workflow engine with one data model, one approval and evidence ledger, and **${packs.length} domain packs** that are`,
  'configuration, not separate apps. Packs are discovered from `src/server/packs/<folder>/pack.ts`; each declares its own',
  'capability system and whether it belongs to the core registry.',
  '',
  '| Capability system | Packs |',
  '|---|---|',
  ...rows,
  '<!-- packs:end -->',
].join('\n');
const readme = readFileSync('README.md', 'utf8');
const a = readme.indexOf('<!-- packs:start -->'); const b = readme.indexOf('<!-- packs:end -->');
if (a < 0 || b < a) throw new Error('README.md: missing <!-- packs:start --> / <!-- packs:end --> markers');
writeFileSync('README.md', readme.slice(0, a) + block + readme.slice(b + '<!-- packs:end -->'.length));
console.log(`README pack block: ${packs.length} packs`);
