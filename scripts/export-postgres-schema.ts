/**
 * Writes db/postgres/schema.sql: RIPPLE's schema in a form Postgres (e.g. Supabase) accepts, generated from the SQLite
 * schema the server runs today (src/server/db/schema.ts). The runtime is still SQLite; this file is the starting point
 * for the Supabase adapter. Usage: npx tsx scripts/export-postgres-schema.ts
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { SCHEMA } from '../src/server/db/schema.js';

const pg = SCHEMA
  .replace(/--[^\n]*\n/g, '\n')                 // drop SQL comments
  .replace(/\bINTEGER PRIMARY KEY\b/g, 'BIGINT PRIMARY KEY')
  .replace(/\n{3,}/g, '\n\n');
const header = `-- GENERATED by scripts/export-postgres-schema.ts from src/server/db/schema.ts (${new Date().toISOString().slice(0, 10)}).\n-- Not yet applied to Supabase: RIPPLE's runtime still uses SQLite. Review before running.\n`;
mkdirSync('db/postgres', { recursive: true });
writeFileSync('db/postgres/schema.sql', header + pg.trim() + '\n');
console.log(`db/postgres/schema.sql: ${(pg.match(/CREATE TABLE/g) ?? []).length} tables`);
