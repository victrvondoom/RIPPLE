/**
 * Step 8: render the documents whose numbers come from the benchmark, so no number in them is typed by hand.
 *   docs/benchmarks/PACKAGE_RISK_BENCHMARK.src.md  -> docs/benchmarks/PACKAGE_RISK_BENCHMARK.md (+ generated tables)
 *   README.md: the block between <!-- bench:start --> and <!-- bench:end --> is re-rendered from README.bench.src.md
 *   docs/AUDIT-2026-11-07.md: the block between <!-- bench:start --> and <!-- bench:end --> likewise (AUDIT.bench.src.md)
 * Tokens: {{fmt:path}} where path is a dotted path into results/metrics-heldout.json (default), or prefixed T. (tuning
 * metrics), P. (data/osv-provenance.json), C. (data/controls-provenance.json). Formats: pct (fraction -> 93.9%),
 * pctv (already a percent -> 93.9%), ci ([92.8–94.9]), n (1,973), raw, frac a|b (a/b as %), sum a|b, diff a|b,
 * comp (100 - percent), names list|k (package names from example strings). An unknown path stops the render.
 * Usage: npx tsx bench/pkgguard/08-render-docs.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DATA, RESULTS, ROOT } from './lib.js';

const REPO = join(ROOT, '..', '..');
const load = (f: string) => JSON.parse(readFileSync(f, 'utf8'));
const SRC: Record<string, any> = { M: load(join(RESULTS, 'metrics-heldout.json')), T: load(join(RESULTS, 'metrics-tune.json')), P: load(join(DATA, 'osv-provenance.json')), C: load(join(DATA, 'controls-provenance.json')) };

function get(path: string): any {
  const m = /^([TPC])\.(.*)$/.exec(path); const root = m ? SRC[m[1]] : SRC.M; const rest = m ? m[2] : path;
  let v: any = root;
  // Keys may contain dots or spaces (e.g. '<1 day'); a segment in [brackets] is taken literally.
  for (const seg of rest.match(/\[[^\]]+\]|[^.]+/g) ?? []) { const k = seg.startsWith('[') ? seg.slice(1, -1) : seg; if (v === null || v === undefined || !(k in v)) throw new Error(`unknown path ${path} (at ${k})`); v = v[k]; }
  return v;
}
/** "popular/vite@8.3.6: 12 [...]", "debounced: name ...", "calc_x (MAL-…): age" -> the package name. */
const pkgName = (s: string) => {
  const t = s.replace(/^(?:popular|longtail|fresh|random|malicious)\//, '').split(/: | \(/)[0];
  const at = t.lastIndexOf('@');
  return at > 0 ? t.slice(0, at) : t;
};
const n = (x: number) => Number(x).toLocaleString('en-US');
const p1 = (x: number) => `${(Math.round(x * 10) / 10).toFixed(1)}%`;
const FMT: Record<string, (args: string[]) => string> = {
  pct: ([a]) => p1(get(a) * 100),
  pctv: ([a]) => p1(get(a)),
  comp: ([a]) => p1(100 - get(a)),
  ci: ([a]) => { const c = get(a); return c ? `[${c[0]}–${c[1]}]` : '[—]'; },
  n: ([a]) => n(get(a)),
  raw: ([a]) => String(get(a)),
  frac: ([a, b]) => p1((get(a) / get(b)) * 100),
  sum: (xs) => n(xs.reduce((s, x) => s + get(x), 0)),
  diff: ([a, b]) => n(get(a) - get(b)),
  short: ([a]) => String(get(a)).slice(0, 8),
  names: ([a, k]) => (get(a) as string[]).slice(0, Number(k ?? 5)).map(pkgName).map((x) => `\`${x}\``).join(', '),
};
export function render(text: string): string {
  return text.replace(/\{\{(\w+):([^}]+)\}\}/g, (_, f: string, args: string) => {
    if (!FMT[f]) throw new Error(`unknown format ${f}`);
    return FMT[f](args.split('|').map((s) => s.trim()));
  });
}
const header = (src: string) => `<!-- GENERATED by bench/pkgguard/08-render-docs.ts from ${src} and bench/pkgguard/results (metrics generated ${SRC.M.generatedAt}). Edit the source, not this file. -->\n`;

// 1) the benchmark report
const reportSrc = join(REPO, 'docs', 'benchmarks', 'PACKAGE_RISK_BENCHMARK.src.md');
const tables = readFileSync(join(RESULTS, 'tables-heldout.md'), 'utf8').split('\n').slice(1).join('\n');
writeFileSync(join(REPO, 'docs', 'benchmarks', 'PACKAGE_RISK_BENCHMARK.md'), header('docs/benchmarks/PACKAGE_RISK_BENCHMARK.src.md') + render(readFileSync(reportSrc, 'utf8')) + '\n' + tables);

// 2) blocks inside hand-written documents
for (const [doc, block] of [['README.md', 'README.bench.src.md'], [join('docs', 'AUDIT-2026-11-07.md'), 'AUDIT.bench.src.md']]) {
  const file = join(REPO, doc); const text = readFileSync(file, 'utf8');
  const a = text.indexOf('<!-- bench:start -->'); const b = text.indexOf('<!-- bench:end -->');
  if (a < 0 || b < a) throw new Error(`${doc}: missing <!-- bench:start --> / <!-- bench:end --> markers`);
  const body = render(readFileSync(join(REPO, 'docs', 'benchmarks', block), 'utf8')).trimEnd();
  writeFileSync(file, `${text.slice(0, a)}<!-- bench:start -->\n<!-- generated from docs/benchmarks/${block} by bench/pkgguard/08-render-docs.ts; edit the source -->\n${body}\n${text.slice(b)}`);
}
console.log('rendered PACKAGE_RISK_BENCHMARK.md, README.md block, AUDIT block');
