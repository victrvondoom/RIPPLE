/**
 * Step 7: render results/tables-<split>.md from results/metrics-<split>.json, so every number in the report is printed
 * by code from the metrics file. Usage: npx tsx bench/pkgguard/07-tables.ts [heldout|tune|all]
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { RESULTS, writeResult } from './lib.js';

const split = process.argv[2] ?? 'heldout';
const M = JSON.parse(readFileSync(join(RESULTS, `metrics-${split}.json`), 'utf8'));
const out: string[] = [];
const p = (x: number | null | undefined) => (x === null || x === undefined ? '—' : `${(x * 100).toFixed(1)}%`);
const ci = (c: number[] | null) => (c ? `[${c[0]}–${c[1]}]` : '');
const h = (t: string) => out.push('', `### ${t}`, '');
const row = (cells: (string | number)[]) => out.push(`| ${cells.join(' | ')} |`);
const head = (cells: string[]) => { row(cells); out.push(`|${cells.map(() => '---').join('|')}|`); };
const cm = (label: string, c: any) => row([label, c.TP, c.FN, c.FP, c.TN, p(c.precision), `${p(c.recall)} ${ci(c.recallCI95)}`, p(c.f1), `${p(c.fpr)} ${ci(c.fprCI95)}`, p(c.fnr)]);
const cmHead = () => head(['Detector / comparison', 'TP', 'FN', 'FP', 'TN', 'Precision*', 'Recall [95% CI]', 'F1*', 'FPR [95% CI]', 'FNR']);

out.push(`<!-- generated by bench/pkgguard/07-tables.ts from results/metrics-${split}.json (${M.generatedAt}); do not edit by hand -->`);
out.push(`Split: **${split}**. Rules: ${M.rules.INSPECT_RULES_VERSION}; reference lists: npm ${M.rules.referenceSizes.npm}, PyPI ${M.rules.referenceSizes.pypi} names. *Precision and F1 depend on the malicious:legitimate mix of each comparison and are not prevalence-adjusted.*`);

h('T1. Lookalike-name rule (name only, no registry data)');
cmHead();
for (const eco of ['npm', 'pypi']) { const x = M.E1_names[eco]; cm(`${eco}: lookalike (distance/separator/scope/homoglyph), ${x.malicious} malicious vs ${x.controls} control names`, x.lookalike); cm(`${eco}: combosquat (affix)`, x.combosquat); }
out.push('', `Most-imitated targets (held-out malicious names): npm ${M.E1_names.npm.topTargets.slice(0, 6).map((t: any) => `${t[0]} (${t[1]})`).join(', ')}; PyPI ${M.E1_names.pypi.topTargets.slice(0, 8).map((t: any) => `${t[0]} (${t[1]})`).join(', ')}.`);
out.push('', `False-alarm examples (control names): npm ${M.E1_names.npm.controlFalseAlarmExamples.slice(0, 5).join('; ')}. PyPI ${M.E1_names.pypi.controlFalseAlarmExamples.slice(0, 5).join('; ')}.`);

const e2 = M.E2_npm_metadata;
h(`T2. npm metadata rules, replayed from registry timestamps (${e2.sample.placedWithTimestamps} of ${e2.sample.malicious} sampled malicious records placed on a timeline)`);
out.push(`Registry status of the sampled malicious packages today: ${Object.entries(e2.sample.statusCounts).map(([k, v]) => `${k} ${v}`).join(', ')}. Controls: ${Object.entries(e2.sample.controls).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '');
cmHead();
cm('composite at FIRST MALICIOUS PUBLISH vs all controls', e2.confusion.atPublish_vs_allControls);
cm('composite at MID LIVE-WINDOW vs all controls', e2.liveWindow.confusion_midWindow_vs_allControls);
cm('composite at FIRST REPORT vs all controls', e2.confusion.atReport_vs_allControls);
for (const g of ['popular', 'longtail', 'fresh']) cm(`at publish vs ${g} controls (snapshot)`, e2.confusion[`atPublish_vs_${g}`]);
for (const g of ['popular', 'longtail', 'fresh']) cm(`at publish vs ${g} controls (at their latest release)`, e2.confusion[`atPublish_vs_${g}_atLatestRelease`]);

h('T3. Each metadata signal: share of packages where it fired (n = packages where the field was known)');
const sig = e2.signals; const keys = Object.keys(sig.maliciousAtPublish);
head(['Signal', 'Malicious @publish', 'Malicious @report', 'Popular', 'Long-tail', 'Fresh (<30 d)']);
for (const k of keys) row([k, ...['maliciousAtPublish', 'maliciousAtReport', 'control_popular', 'control_longtail', 'control_fresh'].map((g) => (sig[g][k].pct === null ? '— (n=0)' : `${sig[g][k].pct}% (n=${sig[g][k].known})`))]);

h('T4. Detection by package age at the first malicious publish, and the control flag rate by age');
head(['Age bucket', 'Malicious n', 'Malicious flagged', 'Control n', 'Control flagged']);
for (const b of ['<1 day', '1-7 days', '7-30 days', '30-365 days', '>1 year']) { const m = e2.detectionByAgeAtPublish[b] ?? { n: 0, pct: null }; const c = e2.controlFlagRateByAge[b] ?? { n: 0, pct: null }; row([b, m.n, m.pct === null ? '—' : `${m.pct}%`, c.n, c.pct === null ? '—' : `${c.pct}%`]); }

h('T5. Detection by number of versions at the first malicious publish');
head(['Versions', 'n', 'Flagged']);
for (const b of ['1', '2', '3-5', '6-20', '>20']) { const m = e2.detectionByVersionsAtPublish[b]; if (m) row([b, m.n, `${m.pct}%`]); }

h('T6. Detection across the live window (install moments from first malicious publish to takedown)');
head(['Moment (fraction of window)', ...e2.liveWindow.byMoment.map((b: any) => String(b.fraction))]);
row(['Flagged', ...e2.liveWindow.byMoment.map((b: any) => `${b.pct}%`)]);
out.push('', `Mean over the window: **${e2.liveWindow.meanDetection}%**. Window length (days): median ${e2.liveWindow.windowDays.median}, p75 ${e2.liveWindow.windowDays.p75}, p90 ${e2.liveWindow.windowDays.p90}.`);

h('T7. New registrations vs malicious versions of existing packages; timing');
const nr = e2.newlyRegistered; const tm = e2.timing;
head(['Measure', 'Value']);
row(['Brand-new package at its first malicious publish (no earlier version)', `${nr.brandNewAtPublish.pct}% of ${nr.brandNewAtPublish.n} ${ci(nr.brandNewAtPublish.ci95)}`]);
row(['… of those, flagged by the composite', `${nr.brandNewDetected.pct}% of ${nr.brandNewDetected.n} ${ci(nr.brandNewDetected.ci95)}`]);
row(['Existing package that received a malicious version', `${nr.existingPackageGotMaliciousVersion.pct}% of ${nr.existingPackageGotMaliciousVersion.n}`]);
row(['… of those, flagged by the composite', `${nr.existingDetected.pct}% of ${nr.existingDetected.n} ${ci(nr.existingDetected.ci95)}`]);
row(['Days from first malicious publish to first report (median / p25 / p75 / p90)', `${tm.daysPublishToReport.median} / ${tm.daysPublishToReport.p25} / ${tm.daysPublishToReport.p75} / ${tm.daysPublishToReport.p90}`]);
row(['Days from first malicious publish to npm takedown (median / p25 / p75 / p90), n', `${tm.daysPublishToTakedown.median} / ${tm.daysPublishToTakedown.p25} / ${tm.daysPublishToTakedown.p75} / ${tm.daysPublishToTakedown.p90}, n=${tm.daysPublishToTakedown.n}`]);
row(['Reported within 7 days of first malicious publish', `${tm.reportedBefore7Days.pct}%`]);

h('T8. Weekly downloads (snapshot; only packages still live; removed packages have no recoverable history here)');
head(['Bucket', 'Malicious still live: n / flagged', 'Popular', 'Long-tail', 'Fresh']);
for (const b of ['<10', '10-49', '50-499', '500-4,999', '>=5,000', 'unknown']) {
  const f = (o: any) => (o?.[b] ? `${o[b].n} / ${o[b].pct}%` : '—');
  row([b, f(e2.downloads.maliciousLive), f(e2.downloads.controls.popular), f(e2.downloads.controls.longtail), f(e2.downloads.controls.fresh)]);
}
out.push('', `"Low downloads" (< 50/week) fired on ${e2.downloads.maliciousLiveLowDownloads.pct}% of ${e2.downloads.maliciousLiveLowDownloads.n} still-live malicious packages with a known count.`);

h('T9. Static code reading only (archives still downloadable; read in memory)');
cmHead();
for (const eco of ['npm', 'pypi']) {
  const x = M.E3_code[eco];
  cm(`${eco} at "review" (score ≥ 4): ${x.sizes.malicious} malicious vs ${Object.entries(x.sizes).filter(([k]) => k !== 'malicious').map(([k, v]) => `${v} ${k}`).join(' + ')}`, x.atReview.vsAllBenign);
  cm(`${eco} at "malicious-looking" (score ≥ 7)`, x.atMalicious.vsAllBenign);
}
out.push('', ...['npm', 'pypi'].map((eco) => { const x = M.E3_code[eco]; return `- ${eco}: false-alarm rate at review by control group: ${Object.entries(x.atReview).filter(([k]) => k.startsWith('fpr_')).map(([k, v]: any) => `${k.slice(4)} ${v.pct}% (${v.hits}/${v.n})`).join(', ')}. Malicious archives with no JavaScript/Python file at all: ${x.maliciousWithoutCodeFile.pct}% (${x.maliciousWithoutCodeFile.hits}/${x.maliciousWithoutCodeFile.n}). Recall at review by reporting source: Amazon Inspector only ${x.recallBySource.amazonInspectorOnly.pct}% (${x.recallBySource.amazonInspectorOnly.hits}/${x.recallBySource.amazonInspectorOnly.n}), other sources ${x.recallBySource.otherSources.pct}% (${x.recallBySource.otherSources.hits}/${x.recallBySource.otherSources.n}) ${ci(x.recallBySource.otherSources.ci95)}.`; }));

const e4 = M.E4_npm_combined;
h(`T10. npm: metadata vs code vs combined, same packages (${e4.atReview.malicious.n} malicious with both a replay and a code reading; ${e4.atReview.benign.n} controls)`);
head(['Outcome (code at review)', 'Malicious', 'Controls']);
for (const k of ['metadataOnly', 'codeOnly', 'both', 'neither']) row([k === 'metadataOnly' ? 'metadata only' : k === 'codeOnly' ? 'code only' : k, e4.atReview.malicious[k], e4.atReview.benign[k]]);
out.push('');
cmHead();
for (const k of ['metadataOnly', 'codeOnly', 'either', 'both']) cm(`${k} (code at review)`, e4.atReview[k]);
for (const k of ['either', 'both']) cm(`${k} (code at malicious-looking)`, e4.atMalicious[k]);

const b = M.E2b_pypi_metadata;
h('T11. PyPI metadata (controls, and the reported projects still live on PyPI, evaluated at report time)');
head(['Group', 'young (<30 d)', 'few versions (≤2)', 'young AND few', 'sdist-only release', 'composite']);
const s = (g: any) => [g.young_package, g.few_versions, g.young_and_few_versions, g.install_script, g.COMPOSITE].map((x: any) => `${x.pct}% (n=${x.known})`);
for (const [g, v] of Object.entries(b.controls)) row([g, ...s(v)]);
if (b.maliciousStillLive) row(['malicious, still live', ...s(b.maliciousStillLive)]);
if (b.confusion_liveMalicious_vs_allControls) { out.push(''); cmHead(); cm('PyPI composite: still-live malicious vs all PyPI controls', b.confusion_liveMalicious_vs_allControls); }

writeResult(`tables-${split}.md`, out.join('\n') + '\n');
console.log(`wrote results/tables-${split}.md (${out.length} lines)`);
